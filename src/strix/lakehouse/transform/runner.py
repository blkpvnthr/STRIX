"""Controlled dbt orchestration.

The runner invokes dbt with a fixed executable and an allow-listed subcommand,
never through a shell and never passing caller-supplied strings to one. Model/
dataset selection is validated against a strict charset, and ``--vars`` is JSON-
encoded. Each run captures ``run_results.json`` + ``manifest.json`` and records the
warehouse publication versions it executed against. This is the only path by which
STRIX runs dbt; arbitrary SQL/shell execution is never exposed to the agent.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from collections.abc import Mapping, Sequence
from pathlib import Path

import duckdb

from strix.errors import LakehouseError
from strix.lakehouse.transform.contracts import DbtNodeResult, DbtRunResult, ModelInfo

# dbt verbs we allow, keyed by the STRIX `transform` subcommand.
_SUBCOMMANDS: dict[str, str] = {
    "deps": "deps",
    "seed": "seed",
    "run": "run",
    "test": "test",
    "build": "build",
    "docs": "docs",
    "parse": "parse",
    "ls": "list",
}
# Selection syntax: identifiers, graph operators (+), method selectors (:), tags
# (@), wildcards (*), paths (/ .), separators (space , -). No shell metacharacters.
_SELECT_RE = re.compile(r"^[A-Za-z0-9_+:*.,@/ -]*$")
_VAR_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_TAIL = 4000


class DbtError(LakehouseError):
    """A dbt invocation could not be run or its results could not be trusted."""


def resolve_project_dir(cli_value: str | None, environ: Mapping[str, str] | None = None) -> Path:
    """Locate the dbt project dir: CLI arg, STRIX_DBT_DIR, else walk up for dbt/."""
    env = os.environ if environ is None else environ
    if cli_value:
        return Path(cli_value)
    if env.get("STRIX_DBT_DIR"):
        return Path(env["STRIX_DBT_DIR"])
    here = Path.cwd()
    for base in (here, *here.parents):
        candidate = base / "dbt"
        if (candidate / "dbt_project.yml").is_file():
            return candidate
    return here / "dbt"


def find_dbt_command() -> list[str]:
    exe = shutil.which("dbt")
    if exe:
        return [exe]
    return [sys.executable, "-m", "dbt.cli.main"]


_PROFILE_TEMPLATE = """\
# Generated by `strix transform init` (gitignored). Credentials, when used, come
# only from SNOWFLAKE_* environment variables via env_var().
strix:
  target: duckdb
  outputs:
    duckdb:
      type: duckdb
      path: "{{ env_var('STRIX_WAREHOUSE_DB') }}"
      threads: 1
      extensions: []
    snowflake:
      type: snowflake
      account: "{{ env_var('SNOWFLAKE_ACCOUNT', '') }}"
      user: "{{ env_var('SNOWFLAKE_USER', '') }}"
      password: "{{ env_var('SNOWFLAKE_PASSWORD', '') }}"
      role: "{{ env_var('SNOWFLAKE_ROLE', 'STRIX_RESEARCH') }}"
      database: "{{ env_var('SNOWFLAKE_DATABASE', 'STRIX') }}"
      warehouse: "{{ env_var('SNOWFLAKE_WAREHOUSE', 'STRIX_WH') }}"
      schema: "{{ env_var('SNOWFLAKE_SCHEMA', 'ANALYTICS') }}"
      threads: 1
"""


class DbtRunner:
    """Runs dbt against the STRIX warehouse with controlled arguments."""

    def __init__(
        self,
        project_dir: Path,
        warehouse_db: Path,
        *,
        backend: str = "duckdb",
        dbt_command: Sequence[str] | None = None,
        environ: Mapping[str, str] | None = None,
    ) -> None:
        self.project_dir = Path(project_dir).resolve()
        self.warehouse_db = Path(warehouse_db).resolve()
        if backend not in ("duckdb", "snowflake"):
            raise DbtError(f"unknown backend {backend!r}")
        self.backend = backend
        self._dbt = list(dbt_command) if dbt_command else find_dbt_command()
        self._base_env = dict(os.environ if environ is None else environ)

    # -- profile generation ------------------------------------------------

    def write_profile(self) -> Path:
        """Write a gitignored profiles.yml into the project dir and return its path."""
        self.project_dir.mkdir(parents=True, exist_ok=True)
        path = self.project_dir / "profiles.yml"
        path.write_text(_PROFILE_TEMPLATE)
        return path

    # -- invocation --------------------------------------------------------

    def _env(self) -> dict[str, str]:
        env = dict(self._base_env)
        env["STRIX_WAREHOUSE_DB"] = str(self.warehouse_db)
        env["DBT_PROFILES_DIR"] = str(self.project_dir)
        # No anonymous usage tracking: keep runs offline, deterministic, and fast.
        env["DBT_SEND_ANONYMOUS_USAGE_STATS"] = "false"
        env["DO_NOT_TRACK"] = "1"
        return env

    def _validate_select(self, select: str | None) -> None:
        if select is not None and not _SELECT_RE.match(select):
            raise DbtError(f"invalid selection expression: {select!r}")

    def _validate_vars(self, variables: Mapping[str, object] | None) -> None:
        for key in variables or {}:
            if not _VAR_KEY_RE.match(key):
                raise DbtError(f"invalid dbt var name: {key!r}")

    def invoke(
        self,
        subcommand: str,
        *,
        select: str | None = None,
        full_refresh: bool = False,
        variables: Mapping[str, object] | None = None,
        extra_args: Sequence[str] | None = None,
        timeout: float | None = None,
    ) -> DbtRunResult:
        if subcommand not in _SUBCOMMANDS:
            raise DbtError(f"unsupported transform subcommand {subcommand!r}")
        self._validate_select(select)
        self._validate_vars(variables)
        dbt_verb = _SUBCOMMANDS[subcommand]

        # `dbt docs` is a command group; `generate` must immediately follow it,
        # before any global options.
        verb_tokens = [dbt_verb, "generate"] if dbt_verb == "docs" else [dbt_verb]
        argv = [
            *self._dbt, *verb_tokens,
            "--project-dir", str(self.project_dir),
            "--profiles-dir", str(self.project_dir),
            "--target", self.backend,
            "--no-use-colors",
        ]
        if select:
            argv += ["--select", select]
        if full_refresh:
            argv.append("--full-refresh")
        if variables:
            argv += ["--vars", json.dumps(dict(variables), sort_keys=True, default=str)]
        if extra_args:
            argv += list(extra_args)

        started = time.monotonic()
        try:
            proc = subprocess.run(  # fixed executable, no shell, validated args
                argv, cwd=self.project_dir, env=self._env(),
                capture_output=True, text=True, timeout=timeout, check=False,
            )
        except FileNotFoundError as exc:
            raise DbtError(
                "dbt is not installed; install the optional extra: pip install -e '.[dbt]'"
            ) from exc
        except subprocess.TimeoutExpired as exc:
            raise DbtError(f"dbt {dbt_verb} timed out after {timeout}s") from exc
        elapsed = time.monotonic() - started

        nodes = self._read_run_results()
        counts = _count(nodes)
        return DbtRunResult(
            command=subcommand, backend=self.backend, dbt_subcommand=dbt_verb,
            argv=tuple(argv), returncode=proc.returncode, success=(proc.returncode == 0),
            elapsed_seconds=round(elapsed, 4), selected=select, full_refresh=full_refresh,
            nodes=tuple(nodes), source_publications=self.source_publications(),
            stdout_tail=proc.stdout[-_TAIL:] if proc.stdout else "",
            stderr_tail=proc.stderr[-_TAIL:] if proc.stderr else "",
            **counts,
        )

    # -- artifact readers --------------------------------------------------

    def _target(self) -> Path:
        return self.project_dir / "target"

    def _read_run_results(self) -> list[DbtNodeResult]:
        path = self._target() / "run_results.json"
        if not path.is_file():
            return []
        try:
            doc = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            return []
        out: list[DbtNodeResult] = []
        for r in doc.get("results", []):
            uid = str(r.get("unique_id", ""))
            out.append(
                DbtNodeResult(
                    unique_id=uid,
                    name=uid.split(".")[-1],
                    resource_type=uid.split(".")[0] if "." in uid else "",
                    status=str(r.get("status", "")),
                    execution_time_seconds=round(float(r.get("execution_time", 0.0)), 4),
                    rows_affected=_rows(r),
                    message=(str(r["message"]) if r.get("message") else None),
                )
            )
        return out

    def model_inventory(self) -> list[ModelInfo]:
        path = self._target() / "manifest.json"
        if not path.is_file():
            return []
        try:
            doc = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            return []
        out: list[ModelInfo] = []
        for uid, node in doc.get("nodes", {}).items():
            if node.get("resource_type") != "model":
                continue
            fqn = node.get("fqn", [])
            layer = fqn[1] if len(fqn) > 1 else "other"
            depends = tuple(
                d.split(".")[-1] for d in node.get("depends_on", {}).get("nodes", [])
            )
            out.append(
                ModelInfo(
                    name=node.get("name", uid.split(".")[-1]),
                    layer=layer,
                    materialization=node.get("config", {}).get("materialized", "view"),
                    schema_name=node.get("schema", ""),
                    depends_on=depends,
                )
            )
        return sorted(out, key=lambda m: (m.layer, m.name))

    def source_publications(self) -> dict[str, str]:
        """Warehouse publication versions (dataset -> silver_publication_id)."""
        if not self.warehouse_db.is_file():
            return {}
        try:
            con = duckdb.connect(str(self.warehouse_db), read_only=True)
        except duckdb.Error:
            return {}
        try:
            tables = {r[0] for r in con.execute("SHOW TABLES").fetchall()}
            if "_load_state" not in tables:
                return {}
            rows = con.execute(
                "SELECT dataset, silver_publication_id FROM _load_state"
            ).fetchall()
            return {str(d): str(p) for d, p in rows}
        finally:
            con.close()


def _rows(result: Mapping[str, object]) -> int | None:
    adapter = result.get("adapter_response")
    if isinstance(adapter, Mapping) and adapter.get("rows_affected") is not None:
        try:
            return int(adapter["rows_affected"])
        except (TypeError, ValueError):
            return None
    return None


def _count(nodes: Sequence[DbtNodeResult]) -> dict[str, int]:
    out = {"pass_count": 0, "fail_count": 0, "error_count": 0, "skip_count": 0}
    for n in nodes:
        s = n.status.lower()
        if s in ("pass", "success"):
            out["pass_count"] += 1
        elif s in ("fail", "warn"):
            out["fail_count"] += 1
        elif s == "error":
            out["error_count"] += 1
        elif s == "skipped":
            out["skip_count"] += 1
    return out
